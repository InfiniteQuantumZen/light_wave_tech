def calculate_real_audio_eigenvalues(audio_tuples, N=16):
    """
    Takes audio tuples [(time, amp), ...], constructs a sliding N x N matrix,
    and computes the max eigenvalue for each frame at C-speed using batch BLAS.
    """
    print(f"Constructing {N}x{N} sliding matrices and calculating eigenvalues...")
    amplitudes = np.array([amp for _, amp in audio_tuples], dtype=np.float32)
    W = N * N # Window size: 16 * 16 = 256

    # Zero-pad the end of the audio track so the sliding window doesn't go out of bounds
    padded_amps = np.pad(amplitudes, (0, W), mode='constant')

    # Fast sliding window view (creates matrix chunks without copying RAM)
    from numpy.lib.stride_tricks import sliding_window_view
    windows = sliding_window_view(padded_amps[:len(amplitudes) + W - 1], W)
    matrices = windows.reshape(-1, N, N)

    # np.linalg.eigvals computes the eigenvalues of ALL matrices simultaneously in parallel
    eigenvalues = np.linalg.eigvals(matrices)
    
    # Take the maximum absolute eigenvalue for each time step
    max_eigs = np.max(np.abs(eigenvalues), axis=-1)

    # Normalize between 0.0 and 1.0
    if np.max(max_eigs) > 0:
        max_eigs = max_eigs / np.max(max_eigs)

    print("Audio eigenvalues successfully calculated.")
    return max_eigs

